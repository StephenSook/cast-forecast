// Copies the published gate results into the app so nothing reads docs/gates at request time.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, "../../docs/gates");
const out = resolve(here, "../src/data/gates");

mkdirSync(out, { recursive: true });
copyFileSync(resolve(src, "k1b-results.json"), resolve(out, "k1b-results.json"));

const readme = readFileSync(resolve(src, "README.md"), "utf8");
writeFileSync(
  resolve(out, "readme.generated.ts"),
  "// Generated by scripts/sync-gates.mjs from docs/gates/README.md. Do not edit.\n" +
    `export const GATES_README: string = ${JSON.stringify(readme)};\n`,
);

// Gate 1's cells, for /api/label-model, which recomputes the held-out error the app's predictions rest on.
const cells = readFileSync(resolve(here, "../../data/plos2025/cells.csv"), "utf8");
const cellsOut = resolve(here, "../src/data/plos2025");
mkdirSync(cellsOut, { recursive: true });
writeFileSync(
  resolve(cellsOut, "cells.generated.ts"),
  "// Generated by scripts/sync-gates.mjs from data/plos2025/cells.csv (CC BY 4.0; see data/plos2025/README.md). Do not edit.\n" +
    `export const CELLS_CSV: string = ${JSON.stringify(cells)};\n`,
);
