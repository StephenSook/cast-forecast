// Copies the published gate results into the app so nothing reads docs/gates at request time.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, "../../docs/gates");
const out = resolve(here, "../src/data/gates");

mkdirSync(out, { recursive: true });
copyFileSync(resolve(src, "k1b-results.json"), resolve(out, "k1b-results.json"));

const readme = readFileSync(resolve(src, "README.md"), "utf8");
writeFileSync(
  resolve(out, "readme.generated.ts"),
  "// Generated by scripts/sync-gates.mjs from docs/gates/README.md. Do not edit.\n" +
    `export const GATES_README: string = ${JSON.stringify(readme)};\n`,
);
